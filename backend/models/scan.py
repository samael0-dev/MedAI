"""Medical Scan ORM Model.

Defines schemas for imaging data (X-ray, MRI, CT, Pathology) and their AI detection results.
"""

import enum
from datetime import datetime
from typing import TYPE_CHECKING, Any, Dict, Optional
from sqlalchemy import (
    DateTime,
    Enum as SQLEnum,
    Float,
    ForeignKey,
    Integer,
    JSON,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from database import Base

if TYPE_CHECKING:
    from .patient import Patient


class ScanType(str, enum.Enum):
    """Supported imaging modalities."""
    XRAY = "XRAY"
    MRI = "MRI"
    CT = "CT"
    PATHOLOGY = "PATHOLOGY"


class AnalysisStatus(str, enum.Enum):
    """Analysis lifecycle states."""
    PENDING = "PENDING"
    PROCESSING = "PROCESSING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


class MedicalScan(Base):
    """Medical scan record containing file reference, modality, and AI findings.

    Attributes:
        id: Unique scan identifier.
        patient_id: Identifier of the corresponding patient.
        scan_type: Imaging modality (XRAY, MRI, CT, PATHOLOGY).
        file_path: Local filesystem or object storage path to the scan file.
        upload_date: Timestamp when file was uploaded.
        analysis_status: Status of the automated ML inference.
        analysis_result: Detailed prediction probabilities, bounding boxes, or heatmap data.
        confidence_score: Primary AI confidence score (0.0 to 1.0).
        findings: High-level textual summary generated by AI pipeline.
        radiologist_notes: Notes and review findings entered by human radiologist.
        created_at: Audit creation timestamp.
    """

    __tablename__ = "medical_scans"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, autoincrement=True)
    patient_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False, index=True
    )
    scan_type: Mapped[ScanType] = mapped_column(
        SQLEnum(ScanType, name="scan_type_enum"), nullable=False, index=True
    )
    file_path: Mapped[str] = mapped_column(String(500), nullable=False)
    upload_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=func.now(), nullable=False
    )
    analysis_status: Mapped[AnalysisStatus] = mapped_column(
        SQLEnum(AnalysisStatus, name="analysis_status_enum"),
        default=AnalysisStatus.PENDING,
        nullable=False,
        index=True,
    )
    analysis_result: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    confidence_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    findings: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    radiologist_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Relationship to Patient
    patient: Mapped["Patient"] = relationship("Patient", back_populates="scans")

    def __repr__(self) -> str:
        return f"<MedicalScan(id={self.id}, patient_id={self.patient_id}, type={self.scan_type}, status={self.analysis_status})>"
